-- The schema the SQLite console had, in PostgreSQL terms. Ids are identity
-- columns BY DEFAULT so the SQLite import can keep every id it copies.

CREATE TABLE users (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	username      TEXT NOT NULL UNIQUE,
	display_name  TEXT NOT NULL DEFAULT '',
	password_hash TEXT NOT NULL,
	salt          TEXT NOT NULL,
	role          TEXT NOT NULL DEFAULT 'member',
	created_at    BIGINT NOT NULL
);

CREATE TABLE api_keys (
	id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	name         TEXT NOT NULL,
	prefix       TEXT NOT NULL,
	key_hash     TEXT NOT NULL,
	created_at   BIGINT NOT NULL,
	last_used_at BIGINT
);
CREATE INDEX api_keys_key_hash ON api_keys (key_hash);
CREATE INDEX api_keys_user ON api_keys (user_id);

-- user_id has no foreign key, as before: deleting an account leaves its
-- conversations for an admin to see.
CREATE TABLE conversations (
	id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id    BIGINT,
	title      TEXT NOT NULL DEFAULT '',
	model      TEXT NOT NULL DEFAULT '',
	params     TEXT NOT NULL DEFAULT '{}',
	pinned     BOOLEAN NOT NULL DEFAULT false,
	created_at BIGINT NOT NULL,
	updated_at BIGINT NOT NULL
);
CREATE INDEX conversations_updated ON conversations (pinned DESC, updated_at DESC);

CREATE TABLE messages (
	id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
	seq             INTEGER NOT NULL,
	role            TEXT NOT NULL,
	content         TEXT NOT NULL DEFAULT '',
	reasoning       TEXT,
	images          TEXT,
	meta            TEXT,
	created_at      BIGINT NOT NULL
);
CREATE INDEX messages_conversation ON messages (conversation_id, seq);

CREATE TABLE settings (
	name  TEXT PRIMARY KEY,
	value BIGINT NOT NULL
);

CREATE TABLE vision_descriptions (
	digest      TEXT PRIMARY KEY,
	model       TEXT NOT NULL,
	description TEXT NOT NULL,
	bytes       BIGINT NOT NULL,
	created_at  DOUBLE PRECISION NOT NULL
);
