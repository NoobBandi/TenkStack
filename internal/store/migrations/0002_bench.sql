-- Benchmark runs (跑分紀錄, §7.6 of the workshop devlog). The whole
-- submission is kept as it was produced; the columns beside it are what the
-- list sorts and filters by. command is the launch command as it was, local
-- only: the export leaves it out.

CREATE TABLE bench_runs (
	id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	model       TEXT NOT NULL,
	name        TEXT NOT NULL DEFAULT '',
	engine      TEXT NOT NULL DEFAULT '',
	tier        TEXT NOT NULL,
	started_at  BIGINT NOT NULL,
	duration_s  DOUBLE PRECISION NOT NULL,
	tuning_hash TEXT NOT NULL DEFAULT '',
	command     TEXT NOT NULL DEFAULT '',
	submission  JSONB NOT NULL,
	created_at  BIGINT NOT NULL
);
CREATE INDEX bench_runs_started ON bench_runs (started_at DESC);
CREATE INDEX bench_runs_model ON bench_runs (model, tier, started_at DESC);
CREATE INDEX bench_runs_tuning ON bench_runs (tuning_hash);
